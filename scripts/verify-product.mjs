import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { writeFile, mkdir } from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
const context=await browser.newContext({locale:'en-US',colorScheme:'light'});
const page=await context.newPage();
await page.goto('http://127.0.0.1:5174/');
await page.locator('#new-note-form textarea').waitFor();
await page.evaluate(async()=>{await navigator.serviceWorker.ready;});
await page.reload();
assert(await page.evaluate(()=>!!navigator.serviceWorker.controller),'Production service worker must control the page');
await page.waitForLoadState('networkidle');
await context.setOffline(true);
await page.reload();
await page.locator('#new-note-form textarea').fill('### Offline check\n\nSaved without a network connection.');
await page.locator('#new-note-form button[type=submit]').click();
await page.getByText('Saved without a network connection.',{exact:true}).waitFor();
await page.reload();
await page.getByText('Saved without a network connection.',{exact:true}).waitFor();
console.log('PASS: Production service worker supports offline reload, writing, saving, and persistent reading after initial online load.');
await mkdir('docs',{recursive:true});
await writeFile('docs/product-offline-check.json',JSON.stringify({testedAt:new Date().toISOString(),source:'Rook Lite 1.6.0 local production build',checks:['Service worker controlling page','Offline reload after online caching','Create and save note offline','Reload and read persisted offline note'],result:'passed',limitation:'Live deployment could not be verified: domain blocked by environment policy. A first visit and missing or cleared cache require connectivity.'},null,2));
await browser.close();
